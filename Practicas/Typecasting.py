#Convierte una variable de un tipo de dato a otro tipo de dato.



#Ejemplo de Typecasting en Python
age = 25  # Variable de tipo entero

print(type(age))  # Imprime el tipo de dato de la variable



# Conversión de entero a float
age = float(age) 

print(age)  # Imprime el valor convertido a float

print(type(age))  # Imprime el tipo de dato de la variable



